/**
 * Черновик документа между сессиями.
 *
 * Редактор работает с одним файлом в памяти вкладки, и до сих пор перезагрузка
 * страницы уносила с собой всю работу. Черновик закрывает самый обидный способ
 * её потерять — случайный F5.
 *
 * Это именно черновик, а не «сохранённый файл»: одна запись без имени и
 * истории. Настоящее сохранение — выгрузка `.conf`, и она остаётся отдельным
 * осознанным действием.
 */

const KEY = 'exeditor.draft';

/**
 * Больше мегабайта в localStorage класть незачем: типичная квота — около
 * пяти, и одинокий редактор не должен её выедать. Такой набор правил всё
 * равно приходит из файла, а не набирается руками.
 */
const LIMIT = 1_000_000;

/** Текст прошлой сессии или `null`, если его нет и восстанавливать нечего. */
export function loadDraft(): string | null {
  try {
    const stored = window.localStorage.getItem(KEY);
    return stored === null || stored === '' ? null : stored;
  } catch {
    // Приватный режим и запрет на хранилище — не повод падать.
    return null;
  }
}

/** Запоминает текст. Пустой документ стирает черновик, а не хранит пустоту. */
export function saveDraft(source: string): void {
  try {
    if (source === '' || source.length > LIMIT) window.localStorage.removeItem(KEY);
    else window.localStorage.setItem(KEY, source);
  } catch {
    // Переполненное хранилище не должно мешать редактировать.
  }
}
